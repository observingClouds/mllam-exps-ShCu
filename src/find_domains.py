"""Find non-overlapping parallelogram sub-domains on the ICON grid at a given level.

Two modes (see README, section "Finding sub-domains"):

    # download the grid topology needed by icon_domains.TriangleTree (~660 MB)
    uv run python src/find_domains.py download-grid --output data/grid_topo.nc

    # all non-overlapping level-7 domains, oriented like domain01 of data/domains.py
    uv run python src/find_domains.py find --grid data/grid_topo.nc --level 7 \
        --reference-domain domain01 --reference-level 8 \
        --output data/domains.level7.py --plot figures/domains.level7.png
"""

import argparse
import importlib.util
import sys
from collections import Counter
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from icon_domains import TriangleTree, load_grid, select_non_overlapping  # noqa: E402


def _load_domains_py(path):
    spec = importlib.util.spec_from_file_location("ref_domains", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.domains


def _write_domains_py(path, doms, level, orientation, reference):
    lines = [
        "# Generated by src/find_domains.py (DVC stage find_domains) -- do not edit by hand.",
        f"# level {level}: {4**level} cells per triangle, {doms[0].n_cells} cells per domain",
        f"# orientation of long diagonal: {orientation:.1f} deg (reference: {reference})",
        f"level = {level}",
        "domains = {",
    ]
    for i, d in enumerate(doms, 1):
        lines.append(f'    "domain{i:02d}": {{"cells": [')
        lines += [f"        slice({s.start}, {s.stop})," for s in d.slices]
        lines.append("    ]},")
    lines.append("}")
    Path(path).write_text("\n".join(lines) + "\n")


def _plot(path, tree, doms, level, orientation):
    import matplotlib

    matplotlib.use("Agg")
    import cartopy.crs as ccrs
    import cartopy.feature as cfeature
    import matplotlib.pyplot as plt
    from matplotlib.patches import Polygon

    pc = ccrs.PlateCarree()
    corners = tree.levels[level]["corners"]
    fig = plt.figure(figsize=(11, 8))
    ax = plt.axes(projection=pc)
    ax.scatter(tree.vlon[::200], tree.vlat[::200], s=0.2, c="#d4d4d4", transform=pc, rasterized=True)
    try:
        ax.add_feature(cfeature.LAND.with_scale("50m"), facecolor="#efe9dc", zorder=0)
        ax.coastlines("50m", lw=0.6, color="#666")
    except Exception as err:  # natural-earth download may fail offline
        print(f"skipping coastlines: {err}")
    for i, d in enumerate(doms, 1):
        for t in d.triangles:
            xy = np.c_[tree.vlon[corners[t]], tree.vlat[corners[t]]]
            ax.add_patch(Polygon(xy, fc="#2a6fdb", alpha=0.3, ec="white", lw=0.3, transform=pc))
        edges = Counter(
            tuple(sorted((int(a), int(b))))
            for t in d.triangles
            for a, b in ((corners[t][0], corners[t][1]), (corners[t][1], corners[t][2]), (corners[t][0], corners[t][2]))
        )
        for (a, b), n in edges.items():
            if n == 1:  # outline = edges used by one triangle only
                ax.plot(tree.vlon[[a, b]], tree.vlat[[a, b]], color="#222", lw=1.0, transform=pc)
        ax.text(tree.vlon[d.center_vertex], tree.vlat[d.center_vertex], f"{i:02d}", ha="center",
                va="center", fontsize=7.5 if len(doms) > 30 else 10, fontweight="bold", transform=pc)
    gl = ax.gridlines(draw_labels=True, lw=0.3, color="#bbb")
    gl.top_labels = gl.right_labels = False
    ax.set_title(f"Level-{level} domains, non-overlapping, orientation {orientation:.0f}°: "
                 f"{len(doms)} × {doms[0].n_cells:,} cells", fontsize=11, loc="left")
    ax.set_extent([tree.vlon.min() - 0.3, tree.vlon.max() + 0.3, tree.vlat.min() - 0.3, tree.vlat.max() + 0.3], crs=pc)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(path, dpi=150, bbox_inches="tight")


def find(args):
    tree = TriangleTree(load_grid(cache=args.grid))
    tree.summary()
    ref_domains = _load_domains_py(args.reference_file)
    ref = tree.domain_from_slices(ref_domains[args.reference_domain]["cells"], args.reference_level)
    orientation = tree.orientation(ref)
    cands = tree.parallelograms(args.level, orientation=orientation)
    doms = select_non_overlapping(cands)
    # number row by row from north-west
    doms.sort(key=lambda d: (-round(tree.vlat[d.center_vertex] * 2) / 2, tree.vlon[d.center_vertex]))
    print(f"level {args.level}: {len(cands)} candidates with orientation {orientation:.1f} deg, "
          f"{len(doms)} non-overlapping domains of {doms[0].n_cells} cells")
    _write_domains_py(args.output, doms, args.level, orientation,
                      f"{args.reference_domain} of {args.reference_file}")
    if args.plot:
        _plot(args.plot, tree, doms, args.level, orientation)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("download-grid", help="download grid topology variables to netCDF")
    p.add_argument("--output", required=True)
    p = sub.add_parser("find", help="find non-overlapping domains at one level")
    p.add_argument("--grid", required=True, help="netCDF from download-grid")
    p.add_argument("--level", type=int, required=True, help="triangle level (4**level cells per triangle)")
    p.add_argument("--reference-file", default="data/domains.py")
    p.add_argument("--reference-domain", default="domain01", help="domain whose orientation is used")
    p.add_argument("--reference-level", type=int, default=8, help="triangle level of the reference domain")
    p.add_argument("--output", required=True, help="python file in the data/domains.py format")
    p.add_argument("--plot", default=None, help="optional map of the domains (png)")
    args = parser.parse_args()
    if args.command == "download-grid":
        load_grid(cache=args.output)
    else:
        find(args)


if __name__ == "__main__":
    main()
